		vamos a poder cargar datos en otra tabla,
		emitir una alerta,
		guardar datos para que esa info se guarde por mail a determinada persona de la empresa,

Lo que nos permite es ir monitoreando la info que se va insertando, actualizando o eliminando en tablas
	como para poder tomar decisiones mas adelante, en relación a la info que se modifico en tal tabla

	Una vez detectado alguno de los eventos en determinada tabla, podemos realizar ciertas acciones

